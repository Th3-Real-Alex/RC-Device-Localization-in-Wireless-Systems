%% titleImage
% Adds the title image to the page
function titleImage(mainContainer)
    ax = uiaxes(mainContainer, ...
        'Position', [600 250 320 300], ...
        'Color', '#f0f0f0', ...
        'MinorGridLineStyle', 'none' ...
    );
    axis(ax, "off");
    [img, ~, alphachannel] = imread('lib/title.png');
    % Image Credit: https://www.mathworks.com/help/phased/ug/device-localization-in-wireless-systems.html
    image(img, 'AlphaData', alphachannel, 'Parent', ax);
end

