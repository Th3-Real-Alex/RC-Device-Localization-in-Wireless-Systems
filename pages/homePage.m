%% homePage.m
% Creates the layout for the home page.
function homePage()
    mainContainer = figure('Name', 'Device Localization in Wireless Systems', ...
        'NumberTitle', 'off', ...
        'Resize', 'off', ...
        'ToolBar', 'none', ...
        'Position', [500 500 1000 600] ...
    );
    
    documentationToolbar(mainContainer);

    % --- UI ---

    title();
    subtitle();

    titleImage(mainContainer);
    buttons(mainContainer);

    footer();
end

